/** Get current language based on page path.
 *  Designer pages → English, everything else → French. */
function getLang() {
  return window.location.pathname.includes('/designer/') ? 'en' : 'fr';
}

/** No-op — language is auto-detected from URL path */
function setLang() {}

/** No-op — no manual toggle */
function toggleLang() {}

/** Get translation for a key */
function t(key, fallback) {
  const lang = getLang();
  return TRANSLATIONS[lang]?.[key] || TRANSLATIONS['fr']?.[key] || fallback || key;
}

/** Translate all elements with data-i18n attribute */
function translatePage() {
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    const val = t(key);
    if (el.tagName === 'INPUT' || el.tagName === 'TEXTAREA') {
      el.placeholder = val;
    } else {
      el.textContent = val;
    }
  });
  // Also translate data-i18n-title for tooltips
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    el.title = t(el.getAttribute('data-i18n-title'));
  });
  // Update html lang attribute
  document.documentElement.lang = getLang();
}

